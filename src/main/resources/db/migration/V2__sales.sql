CREATE TABLE organizations (
  id                      BIGINT       NOT NULL AUTO_INCREMENT COMMENT 'شناسه یکتا',
  version                 BIGINT       NOT NULL DEFAULT 0 COMMENT 'نسخه برای همزمانی',
  created_at              DATETIME(6)  NOT NULL COMMENT 'تاریخ ایجاد',
  updated_at              DATETIME(6)  NOT NULL COMMENT 'تاریخ بروزرسانی',
  created_by              VARCHAR(100) NULL COMMENT 'ایجادکننده',
  updated_by              VARCHAR(100) NULL COMMENT 'بروزرسان',
  name                    VARCHAR(255) NOT NULL COMMENT 'نام سازمان',
  industry                VARCHAR(32)  NULL COMMENT 'صنعت و زمینه فعالیت',
  phone                   VARCHAR(20)  NULL COMMENT 'شماره تلفن',
  email                   VARCHAR(255) NULL COMMENT 'آدرس ایمیل',
  website                 VARCHAR(500) NULL COMMENT 'وب‌سایت',
  city                    VARCHAR(255) NULL COMMENT 'شهر',
  annual_revenue          DECIMAL(19,2) NULL COMMENT 'درآمد سالانه',
  employees               INT          NULL COMMENT 'تعداد کارکنان',
  assigned_to_id          BIGINT       NULL COMMENT 'شناسه کارشناس مسئول',
  address                 VARCHAR(255) NULL COMMENT 'آدرس پستی',
  PRIMARY KEY (id),
  KEY idx_organizations_assigned_to_id (assigned_to_id),
  CONSTRAINT fk_organizations_assigned_to FOREIGN KEY (assigned_to_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='سازمان‌ها و شرکت‌های تجاری';

